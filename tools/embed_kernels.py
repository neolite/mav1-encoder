#!/usr/bin/env python3
"""Flatten src/kernels/*.h (quoted includes inlined once) plus the Metal entry
points into one MSL source, emitted as a C string literal header."""
import os, re, sys

src_dir, out = sys.argv[1], sys.argv[2]
seen = set()

def inline(path):
    path = os.path.normpath(path)
    if path in seen:
        return ''
    seen.add(path)
    res = []
    for line in open(path):
        m = re.match(r'\s*#include\s+"([^"]+)"', line)
        if m:
            res.append(inline(os.path.join(os.path.dirname(path), m.group(1))))
        else:
            res.append(line)
    return ''.join(res)

body = inline(os.path.join(src_dir, 'kernels', 'k_metal_entry.metal'))
with open(out, 'w') as f:
    f.write('/* generated by tools/embed_kernels.py */\nstatic const char kMav1KernelSource[] =\n')
    for line in body.split('\n'):
        f.write('"' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"\n')
    f.write(';\n')
